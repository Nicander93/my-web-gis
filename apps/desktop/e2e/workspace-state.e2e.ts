import { test, expect } from '@playwright/test'

test('focus mode restores table search, scroll, panels and unapplied style draft', async ({ page }) => {
  await page.route('**/*tile.openstreetmap.org/**', route => route.abort())
  await page.goto('/')
  await page.getByRole('button', { name: /^二维地图/ }).click()
  await page.getByRole('tab', { name: '数据', exact: true }).click()
  await page.getByRole('region', { name: '二维功能区' }).getByRole('button', { name: '添加数据', exact: true }).click()
  const content = { type: 'FeatureCollection', features: Array.from({ length: 200 }, (_, index) => ({ type: 'Feature', id: `row-${index}`,
    geometry: { type: 'Point', coordinates: [116 + index / 10000, 39] },
    properties: { name: index < 160 ? `保留-${index}` : `隐藏-${index}`, ...Object.fromEntries(Array.from({ length: 12 }, (_, n) => [`field${n}`, `长属性值-${index}-${n}`])) } })) }
  await page.locator('input[type=file]').setInputFiles({ name: 'workspace.geojson', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(content)) })
  await page.getByRole('dialog', { name: '添加数据', exact: true }).getByRole('button', { name: '确认导入', exact: true }).click()
  await page.getByRole('region', { name: '二维功能区' }).getByRole('button', { name: '添加数据', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'secondary.geojson', mimeType: 'application/json',
    buffer: Buffer.from(JSON.stringify({ type: 'FeatureCollection', features: content.features.slice(0, 1) })) })
  await page.getByRole('dialog', { name: '添加数据', exact: true }).getByRole('button', { name: '确认导入', exact: true }).click()
  await page.locator('.layer-name-button').filter({ hasText: /^workspace$/ }).click()
  await page.getByRole('button', { name: '属性表', exact: true }).click()
  await page.getByLabel('表内搜索', { exact: true }).fill('保留-')
  await page.getByRole('button', { name: '样式', exact: true }).click()
  await page.getByLabel('符号颜色', { exact: true }).fill('#ff0000')
  const activeTable = page.locator('.attribute-table-tab-panel:not([hidden])')
  const table = activeTable.locator('.table-scroll')
  await table.evaluate(element => element.scrollTo({ top: 600, left: 200 }))
  await expect.poll(() => table.evaluate(element => element.scrollTop)).toBe(600)
  const horizontalScroll = await table.evaluate(element => element.scrollLeft)
  await page.getByRole('button', { name: '窗口', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: '专注模式' }).click()
  await expect(table).toBeHidden()
  await expect(page.locator('.style-panel')).toBeHidden()
  await expect(page.locator('.layer-name-button').first()).toBeHidden()
  await page.getByRole('button', { name: '窗口', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: '专注模式' }).click()
  await expect(page.getByLabel('表内搜索', { exact: true })).toHaveValue('保留-')
  await expect(page.getByLabel('符号颜色', { exact: true })).toHaveValue('#ff0000')
  await expect(page.locator('.draft-badge')).toBeVisible()
  await expect(page.locator('.layer-name-button')).toHaveCount(2)
  await expect.poll(() => table.evaluate(element => element.scrollTop)).toBe(600)
  await expect.poll(() => table.evaluate(element => element.scrollLeft)).toBe(horizontalScroll)
  await expect(page.getByLabel('表格状态与分页', { exact: true })).toContainText('显示 160')
  await page.getByLabel('属性表图层', { exact: true }).selectOption({ label: 'secondary' })
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect.poll(() => table.evaluate(element => element.scrollTop)).toBe(0)
  await page.getByLabel('属性表图层', { exact: true }).selectOption({ label: 'workspace' })
  await expect(activeTable.getByLabel('表内搜索', { exact: true })).toHaveValue('保留-')
  await expect.poll(() => table.evaluate(element => element.scrollTop)).toBe(600)
  await expect.poll(() => table.evaluate(element => element.scrollLeft)).toBe(horizontalScroll)
})
