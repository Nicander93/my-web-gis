import { expect, test, type Page } from '@playwright/test'
test.use({ actionTimeout: 15_000, screenshot: 'off', trace: { mode: 'retain-on-failure', screenshots: false } })
async function snapshot(page: Page) { return page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().getSnapshot()) }
async function open(page: Page, name: string) {
  await page.getByRole('button', { name: '窗口', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name, exact: true }).click()
}
test.beforeEach(async ({ page, context }) => {
  test.setTimeout(120_000)
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.route('**/*tile.openstreetmap.org/**', route => route.abort())
  await page.goto('/')
})

test('real import logs, error filtering, clipboard, diagnostics and docking keep project data unchanged', async ({ page }) => {
  test.setTimeout(120_000)
  await page.getByRole('button', { name: /^二维地图/ }).click()
  await page.getByRole('tab', { name: '数据', exact: true }).click()
  await page.getByRole('region', { name: '二维功能区' }).getByRole('button', { name: '添加数据', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'points.geojson', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ type: 'Point', coordinates: [116, 39] })) })
  await page.getByRole('button', { name: '确认导入', exact: true }).click()
  const before = await snapshot(page)
  await open(page, '任务日志')
  const panel = page.getByRole('complementary', { name: '任务与诊断面板' })
  await expect(panel.getByRole('button', { name: '解析 GeoJSON', exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: '导入数据', exact: true })).toBeVisible()
  await panel.getByRole('button', { name: '解析 GeoJSON', exact: true }).click()
  await expect(panel.getByRole('region', { name: '任务详情' })).toContainText('等待确认导入')
  await panel.getByRole('button', { name: '复制任务详情', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('解析完成：1 个图层，1 个要素')
  await page.evaluate(async () => { await (await import('/src/services/import.ts')).importGeoJson(new File(['bad JSON'], 'broken.json')) })
  await panel.getByRole('combobox', { name: '任务状态筛选' }).click()
  await page.getByRole('option', { name: '失败', exact: true }).click()
  await expect(panel.getByRole('button', { name: '导入数据', exact: true })).toHaveCount(0)
  await expect(panel.getByRole('row').filter({ hasText: '解析 GeoJSON' })).toContainText('失败')
  await panel.getByRole('tab', { name: '诊断', exact: true }).click()
  await expect(panel).toContainText('二维要素数')
  await panel.getByRole('button', { name: '刷新诊断', exact: true }).click()
  await panel.getByRole('button', { name: '复制诊断信息', exact: true }).click()
  const report = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()))
  expect(report.project).toMatchObject({ layers: 1, features: 1 })
  expect(report.environment).toMatchObject({ engine: 'OpenLayers', running: true })
  await panel.getByRole('combobox', { name: '任务与诊断停靠位置' }).selectOption('floating')
  await expect(panel.getByRole('button', { name: '停靠任务与诊断', exact: true })).toBeVisible()
  await panel.getByRole('button', { name: '停靠任务与诊断', exact: true }).click()
  expect(await snapshot(page)).toEqual(before)
})

test('log cancellation terminates a real import and clearing preserves active tasks', async ({ page }) => {
  await page.getByRole('button', { name: /^二维地图/ }).click()
  await open(page, '任务日志')
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/services/import.worker.ts*', async route => { await gate; await route.continue().catch(() => {}) })
  const before = await snapshot(page)
  try {
    await page.evaluate(async () => {
      const { importGeoJson } = await import('/src/services/import.ts')
      void importGeoJson(new File(['{"type":"Point","coordinates":[116,39]}'], 'pending.json')).catch(() => {})
    })
    const panel = page.getByRole('complementary', { name: '任务与诊断面板' })
    await expect(panel.getByRole('button', { name: '取消任务', exact: true })).toBeVisible()
    await panel.getByRole('button', { name: '清空已结束记录', exact: true }).click()
    await expect(panel.getByRole('button', { name: '取消任务', exact: true })).toBeVisible()
    await panel.getByRole('button', { name: '取消任务', exact: true }).click()
    release()
    await expect(panel.getByRole('row').filter({ hasText: '解析 GeoJSON' })).toContainText('已取消')
    await expect(panel.getByRole('button', { name: '取消任务', exact: true })).toHaveCount(0)
    expect(await snapshot(page)).toEqual(before)
    await page.evaluate(async () => {
      const store = (await import('/src/stores/project.store.ts')).useProjectStore.getState()
      const replacement = store.getSnapshot(); replacement.project.id = 'another-project'; store.loadSnapshot(replacement)
    })
    await expect(panel.getByRole('button', { name: '解析 GeoJSON', exact: true })).toHaveCount(0)
    await expect(panel).toContainText('暂无任务记录')
  } finally { release() }
})

test('3D resource failures appear in both diagnostics and task logs and navigate to the source inspector', async ({ page }) => {
  test.setTimeout(120_000)
  await page.getByRole('button', { name: /^三维场景/ }).click()
  await expect(page.locator('.scene3d-footer__state')).toHaveText('就绪', { timeout: 30_000 })
  await page.route('**/missing.glb', route => route.fulfill({ status: 404, body: 'missing' }))
  await page.evaluate(async () => { (await import('/src/features/scene3d/scene3d-commands.ts')).addSceneAsset('model', `${location.origin}/missing.glb`, 'Missing model') })
  await open(page, '任务日志')
  const panel = page.getByRole('complementary', { name: '任务与诊断面板' })
  await expect(panel.getByRole('row').filter({ hasText: '加载资源：Missing model' })).toContainText('失败', { timeout: 30_000 })
  const before = await snapshot(page)
  await panel.getByRole('tab', { name: '诊断', exact: true }).click()
  await expect(panel).toContainText('存在加载失败的资源')
  await expect(panel.getByRole('row').filter({ hasText: 'Missing model' })).toContainText('失败')
  await panel.getByRole('button', { name: 'Missing model', exact: true }).click()
  await expect(page.locator('.scene3d-properties')).toContainText('数据源')
  await panel.getByRole('button', { name: '复制诊断信息', exact: true }).click()
  const report = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()))
  expect(report.resources[0]).toMatchObject({ name: 'Missing model', state: 'error' })
  expect(report.environment.engine).toBe('Cesium')
  expect(await snapshot(page)).toEqual(before)
})
