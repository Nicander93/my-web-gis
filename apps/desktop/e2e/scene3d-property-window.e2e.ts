import { expect, test, type Page } from '@playwright/test'

async function names(page: Page) {
  return page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().project.city?.nodes.map(node => node.name))
}

test('modeless properties bind an ID, apply atomically, cancel drafts and pin the inspector', async ({ page }, testInfo) => {
  test.setTimeout(90_000)
  await page.route('**/*tile.openstreetmap.org/**', route => route.abort())
  await page.goto('/')
  await page.getByRole('button', { name: /^三维场景/ }).click()
  await expect(page.locator('.scene3d-footer__state')).toHaveText('就绪', { timeout: 30_000 })
  const nodes = ['Alpha', 'Beta'].map((name, index) => ({ type: 'graphic', id: name, name, visible: true, geometry: { type: 'point', heightMode: 'ground', positions: [[116.391 + index * .001, 39.907, 0]] }, properties: {}, style: { color: '#2f7655', width: 3, pointSize: 8 } }))
  const scene = { version: 3, id: 'properties', title: 'Properties', activeView: 'scene', resources: {}, nodes, views: { scene: { type: '3d', heightReference: 'ellipsoid', camera: { position: [116.391, 39.902, 1600], heading: 0, pitch: -48, roll: 0 } } } }
  await page.getByRole('button', { name: '文件', exact: true }).click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('menuitem', { name: '导入场景', exact: true }).click()
  await (await chooser).setFiles({ name: 'properties.scene.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(scene)) })
  const rows = page.locator('.scene3d-layer-row__select')
  await expect(rows).toHaveCount(2)
  await rows.nth(0).click({ button: 'right' })
  await page.getByRole('menuitem', { name: '完整属性', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '完整属性：Alpha', exact: true })
  await dialog.getByRole('textbox', { name: '对象名称', exact: true }).fill('Applied Alpha')
  expect(await names(page)).toEqual(['Alpha', 'Beta'])
  await rows.nth(1).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '应用', exact: true }).click()
  await expect.poll(() => names(page)).toEqual(['Applied Alpha', 'Beta'])
  await dialog.getByRole('textbox', { name: '对象名称', exact: true }).fill('Discarded')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect.poll(() => names(page)).toEqual(['Applied Alpha', 'Beta'])
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect.poll(() => names(page)).toEqual(['Alpha', 'Beta'])
  await rows.nth(0).click({ button: 'right' })
  await page.getByRole('menuitem', { name: '对象属性', exact: true }).click()
  const inspector = page.getByRole('complementary', { name: '检查器面板' })
  await inspector.getByRole('button', { name: '固定检查器', exact: true }).click()
  await inspector.getByLabel('点大小（像素）', { exact: true }).fill('17')
  await rows.nth(1).click()
  await expect(inspector.locator('input[name="object-name"]')).toHaveValue('Alpha')
  await expect(inspector.getByLabel('点大小（像素）', { exact: true })).toHaveValue('17')
  await inspector.locator('input[name="object-name"]').fill('Pinned Alpha')
  await inspector.locator('input[name="object-name"]').press('Tab')
  await expect.poll(() => names(page)).toEqual(['Pinned Alpha', 'Beta'])
  await inspector.getByRole('button', { name: '取消固定', exact: true }).click()
  await expect(inspector.locator('input[name="object-name"]')).toHaveValue('Beta')
  await rows.nth(0).click({ button: 'right' })
  await page.getByRole('menuitem', { name: '完整属性', exact: true }).click()
  const second = page.getByRole('dialog', { name: '完整属性：Pinned Alpha', exact: true })
  await second.getByRole('textbox', { name: '对象名称', exact: true }).fill('Stale draft')
  await inspector.locator('input[name="object-name"]').fill('External Alpha')
  await inspector.locator('input[name="object-name"]').press('Tab')
  await second.getByRole('button', { name: '应用', exact: true }).click()
  await expect(second.getByText('对象已被其他操作修改，请重新载入后编辑。')).toBeVisible()
  await expect.poll(() => names(page)).toEqual(['External Alpha', 'Beta'])
  await second.getByRole('button', { name: '重新载入', exact: true }).click()
  await expect(second.getByRole('textbox', { name: '对象名称', exact: true })).toHaveValue('External Alpha')
  await second.getByRole('menuitem', { name: '数据属性', exact: true }).click()
  await second.getByRole('button', { name: '添加属性', exact: true }).click()
  await expect(second.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await second.getByRole('textbox', { name: '字段名 1', exact: true }).fill('note')
  await second.getByRole('textbox', { name: '字段值 1', exact: true }).fill('Object-bound draft')
  await second.getByRole('menuitem', { name: '属性弹窗', exact: true }).click()
  await second.getByRole('textbox', { name: '弹窗标题', exact: true }).fill('Alpha popup')
  await second.getByRole('button', { name: '添加弹窗字段', exact: true }).click()
  await second.getByRole('menuitem', { name: '常规与位置', exact: true }).click()
  await second.getByRole('textbox', { name: '对象名称', exact: true }).fill('Final Alpha')
  await second.getByRole('button', { name: '确定', exact: true }).click()
  await expect(second).toHaveCount(0)
  await expect.poll(() => names(page)).toEqual(['Final Alpha', 'Beta'])
  const applied = await page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().project.city?.nodes[0])
  expect(applied).toMatchObject({ properties: { note: 'Object-bound draft' }, popup: { title: 'Alpha popup', fields: [{ field: 'name', label: '名称' }] } })
})
