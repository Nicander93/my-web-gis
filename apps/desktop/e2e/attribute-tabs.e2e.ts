import { test, expect, type Page } from '@playwright/test'

async function importRows(page: Page, name: string) {
  await page.getByRole('tab', { name: '数据', exact: true }).click()
  await page.getByRole('region', { name: '二维功能区' }).getByRole('button', { name: '添加数据', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: `${name}.geojson`, mimeType: 'application/json',
    buffer: Buffer.from(JSON.stringify({ type: 'FeatureCollection', features: [2, 0, 4].map((value, index) => ({
      type: 'Feature', id: `${name}-${index}`, properties: { value, code: '001' },
      geometry: { type: 'Point', coordinates: [116 + index, 39] }
    })) })) })
  await page.getByRole('button', { name: '确认导入', exact: true }).click()
}

test('table tabs retain drafts; typed field calculation rolls back and uses one undo step', async ({ page }, info) => {
  await page.route('**/*tile.openstreetmap.org/**', (route) => route.abort())
  await page.goto('/')
  await page.getByRole('button', { name: /^二维地图/ }).click()
  await importRows(page, 'first')
  await page.getByRole('button', { name: '属性表', exact: true }).click()
  const panel = () => page.locator('.attribute-table-tab-panel:visible')
  await panel().getByLabel('表内搜索').fill('001')
  await panel().getByRole('button', { name: /^图层过滤/ }).click()
  const filter = panel().getByLabel('图层字段过滤')
  await filter.locator('select').nth(0).selectOption('value')
  await filter.locator('input').fill('2')
  await filter.getByRole('button', { name: '添加条件', exact: true }).click()
  await importRows(page, 'second')
  await page.getByRole('button', { name: '属性表', exact: true }).click()
  await expect(page.locator('.attribute-table-host').getByRole('tablist').getByRole('tab')).toHaveCount(2)
  await panel().getByLabel('表内搜索').fill('not-found')
  await page.getByRole('tab', { name: 'first', exact: true }).click()
  await expect(panel().getByLabel('表内搜索')).toHaveValue('001')
  await expect(panel().getByLabel('图层字段过滤').getByRole('button', { name: '应用过滤', exact: true })).toBeEnabled()
  await page.locator('.layer-name-button').filter({ hasText: 'first' }).click()
  await page.getByRole('tab', { name: '编辑', exact: true }).click()
  await page.getByRole('button', { name: '开始编辑', exact: true }).click()
  await panel().getByRole('button', { name: '字段计算', exact: true }).click()
  const calculator = panel().getByLabel('字段计算器', { exact: true })
  await calculator.getByLabel('计算字段名').fill('result')
  await calculator.getByLabel('字段计算表达式').fill('10 / field("value")')
  await calculator.getByRole('button', { name: '应用计算', exact: true }).click()
  await expect(calculator.getByRole('alert')).toContainText('记录 first-1：除数不能为零')
  await expect(panel().getByRole('columnheader', { name: 'result', exact: true })).toHaveCount(0)
  await calculator.getByLabel('字段计算表达式').fill('field("value") * 3')
  await calculator.getByRole('button', { name: '应用计算', exact: true }).click()
  await expect(calculator.getByRole('status')).toContainText('3 条')
  await expect(panel().getByRole('columnheader', { name: 'result', exact: true })).toBeVisible()
  await expect(panel().locator('.table-scroll tbody tr')).toHaveCount(3)
  expect((await panel().locator('.table-scroll').boundingBox())!.height).toBeGreaterThan(40)
  const footerBounds = (await panel().getByLabel('表格状态与分页').boundingBox())!
  const windowBounds = (await page.getByRole('complementary', { name: '属性表面板' }).boundingBox())!
  expect(footerBounds.y + footerBounds.height).toBeLessThanOrEqual(windowBounds.y + windowBounds.height)
  await page.screenshot({ path: info.outputPath('antd-field-calculator.png') })
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(panel().getByRole('columnheader', { name: 'result', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect(panel().getByRole('columnheader', { name: 'result', exact: true })).toBeVisible()
  await panel().getByRole('button', { name: '字段列表', exact: true }).click()
  await panel().getByLabel('字段列表', { exact: true }).getByLabel('code', { exact: true }).uncheck()
  await expect(panel().getByRole('columnheader', { name: 'code', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'second', exact: true }).click()
  await expect(panel().getByLabel('表内搜索')).toHaveValue('not-found')
  await page.locator('.ant-tabs-tab').filter({ has: page.getByRole('tab', { name: 'second', exact: true }) })
    .locator('.ant-tabs-tab-remove').click()
  await expect(page.getByRole('tab', { name: 'first', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.screenshot({ path: info.outputPath('table-calculator.png') })
})
