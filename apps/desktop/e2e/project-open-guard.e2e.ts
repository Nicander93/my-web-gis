import { test, expect } from '@playwright/test'

test('a project chosen after another edit cannot overwrite the current document or its history', async ({ page }, info) => {
  await page.route('**/*tile.openstreetmap.org/**', (route) => route.abort())
  await page.goto('/')
  await page.getByRole('button', { name: /^二维地图/ }).click()
  await page.getByRole('tab', { name: '数据', exact: true }).click()
  await page.getByRole('region', { name: '二维功能区' }).getByRole('button', { name: '添加数据', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'guard.geojson', mimeType: 'application/json',
    buffer: Buffer.from('{"type":"FeatureCollection","features":[{"type":"Feature","id":"guard-row","properties":{"value":2},"geometry":{"type":"Point","coordinates":[116,39]}}]}') })
  await page.getByRole('button', { name: '确认导入', exact: true }).click()
  await page.getByRole('button', { name: '属性表', exact: true }).click()
  await page.getByRole('tab', { name: '编辑', exact: true }).click()
  await page.getByRole('button', { name: '开始编辑', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  const path = info.outputPath('old-version.webgis.json')
  await (await download).saveAs(path)
  await page.getByRole('button', { name: '文件', exact: true }).click()
  const selecting = page.waitForEvent('filechooser')
  await page.getByRole('menuitem', { name: /^打开/ }).click()
  const chooser = await selecting
  const panel = page.locator('.attribute-table-tab-panel:visible')
  await panel.locator('tbody tr[data-feature-id="guard-row"] td').nth(3).dblclick()
  await panel.locator('.cell-editor').fill('99')
  await panel.locator('.cell-editor').press('Enter')
  const edited = await page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().getSnapshot())
  await chooser.setFiles(path)
  await expect(page.getByText('打开失败：选择或读取文件期间工程已改变，原内容保留', { exact: true })).toBeVisible()
  expect(await page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().getSnapshot())).toEqual(edited)
  expect(await page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().dirty)).toBe(true)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(panel.locator('tbody')).toContainText('2')
  expect(await page.evaluate(async () => {
    const state = (await import('/src/stores/project.store.ts')).useProjectStore.getState()
    return Object.values(state.featuresByDataset).flat()[0].properties.value
  })).toBe(2)
})

test('new and open decisions preserve unapplied styles until an explicit draft choice', async ({ page }, info) => {
  await page.route('**/*tile.openstreetmap.org/**', (route) => route.abort())
  await page.goto('/')
  await page.getByRole('button', { name: /^二维地图/ }).click()
  await page.getByRole('tab', { name: '数据', exact: true }).click()
  await page.getByRole('region', { name: '二维功能区' }).getByRole('button', { name: '添加数据', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'styles.geojson', mimeType: 'application/json',
    buffer: Buffer.from('{"type":"FeatureCollection","features":[{"type":"Feature","id":"style-row","properties":{"value":2},"geometry":{"type":"Point","coordinates":[116,39]}}]}') })
  await page.getByRole('button', { name: '确认导入', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  const path = info.outputPath('before-style-draft.webgis.json')
  await (await downloading).saveAs(path)
  const before = await page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().getSnapshot())
  await page.getByRole('button', { name: '样式', exact: true }).click()
  await page.getByLabel('符号颜色', { exact: true }).fill('#ff0000')
  await page.getByRole('button', { name: '文件', exact: true }).click()
  await page.getByRole('menuitem', { name: /^新建/ }).click()
  const creating = page.getByRole('dialog', { name: '新建项目', exact: true })
  await creating.getByRole('button', { name: '创建项目', exact: true }).click()
  const drafts = page.getByRole('dialog', { name: '处理未应用样式', exact: true })
  await expect(drafts).toBeVisible()
  await drafts.getByRole('button', { name: '取消操作', exact: true }).click()
  await expect(creating).toBeVisible()
  expect(await page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().getSnapshot())).toEqual(before)
  await creating.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByLabel('符号颜色', { exact: true })).toHaveValue('#ff0000')
  await page.getByRole('button', { name: '文件', exact: true }).click()
  await page.getByRole('menuitem', { name: /^打开/ }).click()
  await expect(drafts).toBeVisible()
  await drafts.getByRole('button', { name: '取消操作', exact: true }).click()
  expect(await page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().getSnapshot())).toEqual(before)
  await page.getByRole('button', { name: '文件', exact: true }).click()
  await page.getByRole('menuitem', { name: /^打开/ }).click()
  const choosing = page.waitForEvent('filechooser')
  await drafts.getByRole('button', { name: '放弃草稿并继续', exact: true }).click()
  await (await choosing).setFiles(path)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.layer-name-button')).toContainText('styles')
  expect(await page.evaluate(async () => {
    const { useSessionStore } = await import('/src/stores/session.store.ts')
    return Object.values(useSessionStore.getState().sessions).some((session) => session.styleDraft?.dirty)
  })).toBe(false)
})
