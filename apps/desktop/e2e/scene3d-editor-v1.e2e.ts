import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function openTileset(page: Page) {
  await page.route('**/*tile.openstreetmap.org/**', route => route.abort())
  await page.goto('/')
  await page.getByRole('button', { name: /^三维场景/ }).click()
  await expect(page.locator('.scene3d-footer__state')).toHaveText('就绪', { timeout: 30_000 })
  await page.getByRole('button', { name: '使用三维示例', exact: true }).click()
  const row = page.locator('.scene3d-layer-row').filter({ hasText: '建筑场景' })
  await expect(row.locator('small')).toHaveText('3D Tiles', { timeout: 30_000 })
  await row.locator('.scene3d-layer-row__select').click()
  const id = await page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().project.city!.nodes[0].id)
  return { row, id, inspector: page.getByRole('complementary', { name: '检查器面板' }), rail: page.getByRole('navigation', { name: '右侧工作面板' }) }
}

async function node(page: Page) {
  return page.evaluate(async () => (await import('/src/stores/project.store.ts')).useProjectStore.getState().project.city!.nodes[0])
}
async function presentation(page: Page, id: string) {
  return page.evaluate(async id => (await import('/src/features/scene3d/scene3d-runtime-host.ts')).getLiveSceneDiagnostics(id)?.presentation?.tileset, id)
}

test('3D workrail, searchable API parameters and runtime-only actions share the desktop interaction model', async ({ page }) => {
  const { inspector, rail, id } = await openTileset(page)
  await expect(inspector).toBeHidden()
  await rail.getByRole('button', { name: '属性', exact: true }).click()
  await expect(inspector.getByRole('tab', { name: '配置', exact: true })).toBeVisible()
  const input = inspector.getByRole('spinbutton', { name: 'maximumScreenSpaceError', exact: true })
  await input.fill('2'); await input.fill('4'); await input.fill('8')
  expect(await node(page)).not.toHaveProperty('maximumScreenSpaceError')
  await input.press('Tab')
  await expect.poll(() => node(page)).toMatchObject({ maximumScreenSpaceError: 8 })
  await expect.poll(() => presentation(page, id)).toMatchObject({ maximumScreenSpaceError: 8, cacheBytes: 268435456 })
  await inspector.getByLabel('搜索参数', { exact: true }).fill('动态')
  await expect(input).toBeHidden()
  await expect(inspector.getByRole('switch', { name: 'dynamicScreenSpaceError', exact: true })).toBeVisible()
  await inspector.getByLabel('搜索参数', { exact: true }).fill('')
  const before = await node(page)
  await inspector.locator('summary').filter({ hasText: '运行诊断' }).click()
  await inspector.getByRole('button', { name: '刷新诊断', exact: true }).click()
  await inspector.getByRole('button', { name: '卸载未使用瓦片', exact: true }).click()
  expect(await node(page)).toEqual(before)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  expect(await node(page)).not.toHaveProperty('maximumScreenSpaceError')
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect.poll(() => node(page)).toMatchObject({ maximumScreenSpaceError: 8 })
  await rail.getByRole('button', { name: '场景', exact: true }).click()
  const snapshot = await page.evaluate(async () => JSON.stringify((await import('/src/stores/project.store.ts')).useProjectStore.getState().getSnapshot()))
  await inspector.getByRole('switch', { name: '使用屏幕原生像素（高 DPI）', exact: true }).click()
  expect(await page.evaluate(async () => JSON.stringify((await import('/src/stores/project.store.ts')).useProjectStore.getState().getSnapshot()))).toBe(snapshot)
  await rail.getByRole('button', { name: '场景', exact: true }).click()
  await expect(inspector).toBeHidden()
})

test('native style drafts preview safely, survive highlight, history, scene export and reopen', async ({ page }) => {
  test.setTimeout(90_000)
  const { inspector, rail, row, id } = await openTileset(page)
  await rail.getByRole('button', { name: '属性', exact: true }).click()
  await inspector.getByRole('tab', { name: '样式', exact: true }).click()
  await inspector.getByRole('button', { name: '编辑瓦片样式', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: /^完整属性：/ })
  const parameter = dialog.getByRole('spinbutton', { name: 'maximumScreenSpaceError', exact: true })
  await parameter.fill('')
  await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await dialog.getByRole('menuitem', { name: '常规与位置', exact: true }).click()
  await dialog.getByRole('menuitem', { name: '样式与参数', exact: true }).click()
  await expect(parameter).toHaveValue('')
  await parameter.press('Escape')
  await expect(parameter).toHaveValue('16')
  await dialog.getByText('Style JSON', { exact: true }).click()
  const json = dialog.getByRole('textbox', { name: 'Cesium3DTileStyle JSON', exact: true })
  await json.fill('{"color":')
  await expect(dialog.getByRole('button', { name: '应用', exact: true })).toBeDisabled()
  expect(await node(page)).not.toHaveProperty('style')
  await json.fill(JSON.stringify({ color: '${Height} > 30 ? color("red") : color("white")' }))
  await dialog.getByRole('button', { name: '应用', exact: true }).click()
  await expect(dialog.getByText('3D Tiles Style 无法应用于当前已加载要素', { exact: true })).toBeVisible()
  expect(await node(page)).not.toHaveProperty('style')
  await expect(page.locator('.cesium-widget-errorPanel')).toHaveCount(0)
  const style = { defines: { height: '42' }, color: { conditions: [['${height} > 30', 'color("red")'], ['true', 'color("white")']] }, meta: { title: '${name}' } }
  await json.fill(JSON.stringify(style))
  await dialog.getByRole('switch', { name: '实时预览', exact: true }).click()
  await expect.poll(() => presentation(page, id)).toMatchObject({ style, highlighted: true })
  expect(await node(page)).not.toHaveProperty('style')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect.poll(async () => (await presentation(page, id))?.style).toBeUndefined()
  await inspector.getByRole('button', { name: '编辑瓦片样式', exact: true }).click()
  dialog = page.getByRole('dialog', { name: /^完整属性：/ })
  await dialog.getByText('Style JSON', { exact: true }).click()
  await dialog.getByRole('textbox', { name: 'Cesium3DTileStyle JSON', exact: true }).fill(JSON.stringify(style))
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect.poll(() => node(page)).toMatchObject({ style })
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  expect(await node(page)).not.toHaveProperty('style')
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect.poll(() => node(page)).toMatchObject({ style })
  await inspector.getByRole('button', { name: '编辑瓦片样式', exact: true }).click()
  dialog = page.getByRole('dialog', { name: /^完整属性：/ })
  await dialog.getByRole('switch', { name: '实时预览', exact: true }).click()
  await dialog.getByRole('button', { name: '清除持久样式', exact: true }).click()
  await expect.poll(async () => (await presentation(page, id))?.style).toBeUndefined()
  expect(await node(page)).toMatchObject({ style })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect.poll(() => presentation(page, id)).toMatchObject({ style })
  await row.locator('.scene3d-layer-row__select').click({ modifiers: ['Control'] })
  await expect.poll(() => presentation(page, id)).toMatchObject({ style, nativeStyle: style, highlighted: false })
  await page.getByRole('button', { name: '文件', exact: true }).click()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('menuitem', { name: '导出完整场景', exact: true }).click()
  const exported = JSON.parse(await readFile((await (await downloaded).path())!, 'utf8'))
  expect(exported.nodes.find((node: { type: string }) => node.type === '3dtiles').style).toEqual(style)
  expect(JSON.stringify(exported)).not.toContain('webgis-resource.localhost')
  await page.getByRole('button', { name: '文件', exact: true }).click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('menuitem', { name: '导入场景', exact: true }).click()
  await page.getByRole('button', { name: '放弃修改并打开', exact: true }).click()
  await (await chooser).setFiles({ name: 'styled.scene.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported)) })
  await expect.poll(() => node(page)).toMatchObject({ style })
  await expect.poll(() => presentation(page, id)).toMatchObject({ style, nativeStyle: style })
})

test('CesiumJS export is separate from scene JSON and reports unsupported capabilities', async ({ page }) => {
  await openTileset(page)
  await page.getByRole('button', { name: '文件', exact: true }).click()
  await page.getByRole('menuitem', { name: '导出 CesiumJS 代码', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '导出 CesiumJS 代码', exact: true })
  await expect(dialog.getByRole('button', { name: '保存 JavaScript 模块', exact: true })).toBeEnabled()
  const downloaded = page.waitForEvent('download')
  await dialog.getByRole('button', { name: '保存 JavaScript 模块', exact: true }).click()
  const download = await downloaded
  expect(download.suggestedFilename()).toMatch(/\.cesium\.js$/)
  const code = await readFile((await download.path())!, 'utf8')
  expect(code).toContain("import * as Cesium from 'cesium'")
  expect(code).not.toContain('@desktop-webgis/')
  await page.evaluate(async () => (await import('/src/features/scene3d/scene3d-commands.ts')).addSampleWater())
  await expect(dialog.getByRole('button', { name: '保存 JavaScript 模块', exact: true })).toBeDisabled()
  await expect(dialog.getByText(/水面节点/)).toBeVisible()
})
