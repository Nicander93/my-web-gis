import { test, expect, type Page } from '@playwright/test'

async function windowMenu(page: Page, name: string) {
  await page.getByRole('button', { name: '窗口', exact: true }).click()
  await page.getByRole(name === '重置布局' ? 'menuitem' : 'menuitemcheckbox', { name, exact: true }).click()
}

test.use({ screenshot: 'off', trace: { mode: 'retain-on-failure', screenshots: false } })

test.beforeEach(async ({ page }) => {
  await page.route('**/*tile.openstreetmap.org/**', route => route.abort())
  await page.goto('/')
})

test('2D windows cover a stable full canvas and retain geometry outside project history', async ({ page }, info) => {
  await page.getByRole('button', { name: /^二维地图/ }).click()
  const viewport = page.locator('.map-canvas__viewport')
  const original = await viewport.boundingBox()
  expect(original?.width).toBe(page.viewportSize()?.width)
  await expect(page.getByRole('tab')).toHaveText(['地图', '编辑', '数据', '分析'])
  const workspace = page.getByRole('main', { name: 'GIS Workspace' })
  const root = await workspace.boundingBox()
  const tools = await page.locator('.workbench-ribbon-commands').boundingBox()
  expect(root!.y - (tools!.y + tools!.height)).toBeLessThanOrEqual(2)
  const before = await page.evaluate(async () => {
    const { useProjectStore } = await import('/src/stores/project.store.ts')
    return { snapshot: useProjectStore.getState().getSnapshot(), dirty: useProjectStore.getState().dirty, undo: useProjectStore.getState().canUndoEdit() }
  })
  await windowMenu(page, '检查器')
  await windowMenu(page, '属性表')
  const bottom = page.getByRole('complementary', { name: '属性表面板' })
  expect((await bottom.boundingBox())!.width).toBe(original!.width)
  expect(await viewport.boundingBox()).toEqual(original)
  await page.getByRole('button', { name: '浮动属性表', exact: true }).click()
  const title = page.getByLabel('移动属性表窗口', { exact: true })
  const box = (await title.boundingBox())!
  const beforeDrag = (await bottom.boundingBox())!
  await page.mouse.move(box.x + 20, box.y + 15)
  await page.mouse.down()
  await page.mouse.move(box.x + 100, box.y - 65, { steps: 6 })
  await page.mouse.up()
  expect((await bottom.boundingBox())!.y).toBeLessThan(beforeDrag.y)
  await title.focus()
  const saved = (await bottom.boundingBox())!
  await page.keyboard.press('ArrowRight')
  await expect.poll(async () => (await bottom.boundingBox())!.x).toBe(saved.x + 5)
  const moved = (await bottom.boundingBox())!
  const resize = page.getByRole('separator', { name: '调整属性表窗口大小', exact: true })
  await resize.focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(async () => (await bottom.boundingBox())!.width).toBe(moved.width + 10)
  await page.getByRole('button', { name: '最大化属性表', exact: true }).click()
  expect((await bottom.boundingBox())!.width).toBe(root!.width)
  expect((await bottom.boundingBox())!.height).toBe(root!.height)
  await page.getByRole('button', { name: '还原属性表', exact: true }).click()
  await page.getByRole('button', { name: '关闭属性表窗口', exact: true }).click()
  await expect(bottom).toBeHidden()
  await expect(page.locator('.restore-trigger,.scene3d-panel-restore')).toHaveCount(0)
  await windowMenu(page, '属性表')
  expect(await viewport.boundingBox()).toEqual(original)
  const after = await page.evaluate(async () => {
    const { useProjectStore } = await import('/src/stores/project.store.ts')
    return { snapshot: useProjectStore.getState().getSnapshot(), dirty: useProjectStore.getState().dirty, undo: useProjectStore.getState().canUndoEdit() }
  })
  expect(after).toEqual(before)
  const persisted = await bottom.boundingBox()
  await page.reload()
  await page.getByRole('button', { name: /^二维地图/ }).click()
  expect(await bottom.boundingBox()).toEqual(persisted)
  await windowMenu(page, '重置布局')
  await expect(bottom).toBeHidden()
  await expect(page.getByRole('complementary', { name: '检查器面板' })).toBeHidden()
  await expect(page.getByRole('complementary', { name: '图层面板' })).toBeVisible()
})

test('drag cancellation and small-screen restoration keep window controls reachable', async ({ page }) => {
  await page.getByRole('button', { name: /^二维地图/ }).click()
  const panel = page.getByRole('complementary', { name: '图层面板' })
  const original = await panel.boundingBox()
  const title = page.getByLabel('移动图层窗口', { exact: true })
  const rect = (await title.boundingBox())!
  await page.mouse.move(rect.x + 25, rect.y + 15)
  await page.mouse.down()
  await page.mouse.move(rect.x + 450, rect.y + 200, { steps: 5 })
  await page.keyboard.press('Escape')
  await page.mouse.up()
  expect(await panel.boundingBox()).toEqual(original)
  await page.getByRole('button', { name: '浮动图层', exact: true }).click()
  await title.focus()
  for (let index = 0; index < 50; index++) await page.keyboard.press('Shift+ArrowRight')
  await page.setViewportSize({ width: 800, height: 550 })
  await expect.poll(async () => { const b = (await panel.boundingBox())!; return b.x + b.width }).toBeLessThanOrEqual(800)
  const bounds = (await panel.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(800)
  const close = panel.getByRole('button', { name: '收起图层面板', exact: true })
  await expect(close).toBeVisible()
  await close.click()
  await expect(panel).toBeHidden()
  await windowMenu(page, '图层面板')
  await expect(close).toBeVisible()
})

test('3D uses the same menus and docking without resizing or recreating Cesium', async ({ page }, info) => {
  await page.getByRole('button', { name: /^三维场景/ }).click()
  const canvas = page.locator('.scene3d-canvas__viewport canvas')
  await expect(canvas).toBeVisible()
  await expect(page.getByRole('tab')).toHaveText(['场景', '标绘', '编辑', '瓦片', '分析'])
  const original = await canvas.boundingBox()
  const identity = await canvas.evaluate(element => { element.setAttribute('data-identity', 'original'); return 'original' })
  await windowMenu(page, '检查器')
  await page.getByRole('button', { name: '浮动图层属性', exact: true }).click()
  await page.keyboard.press('Control+Shift+F')
  await expect(page.getByRole('complementary', { name: '检查器面板' })).toBeHidden()
  await page.keyboard.press('Control+Shift+F')
  await expect(page.getByRole('complementary', { name: '检查器面板' })).toBeVisible()
  await windowMenu(page, '场景树')
  expect(await canvas.boundingBox()).toEqual(original)
  await expect(canvas).toHaveAttribute('data-identity', identity)
  await expect(page.locator('.restore-trigger,.scene3d-panel-restore')).toHaveCount(0)
})
