import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('production assets execute GeoLibre locally and persist a reusable result', async ({ page, baseURL }, info) => {
  test.setTimeout(120_000)
  page.setDefaultTimeout(15_000)
  const cliResponses: number[] = [], remote: string[] = []
  if (!baseURL) throw new Error('Production preview URL is required')
  page.on('response', response => { if (/\/assets\/geolibre-cli-[^/]+\.wasm$/.test(new URL(response.url()).pathname)) cliResponses.push(response.status()) })
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.hostname.endsWith('tile.openstreetmap.org')) return route.abort()
    if (url.protocol.startsWith('http') && url.origin !== baseURL) { remote.push(url.origin); return route.abort() }
    return route.continue()
  })
  await page.goto('/')
  await page.getByRole('button', { name: /^二维地图/ }).click()
  await page.getByRole('tab', { name: '数据', exact: true }).click()
  await page.getByRole('region', { name: '二维功能区' }).getByRole('button', { name: '添加数据', exact: true }).click()
  const properties = { name: '生产道路', value: 42, nested: { flags: [true, null] } }
  const coordinates = [[116, 39], [116.001, 39.00001], [116.002, 39]]
  await page.locator('input[type=file]').setInputFiles({ name: 'production.geojson', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ type: 'Feature', properties, geometry: { type: 'LineString', coordinates } })) })
  await page.getByRole('button', { name: '确认导入', exact: true }).click()
  const baselineDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  const baselineFile = info.outputPath('before-processing.webgis.json')
  await (await baselineDownload).saveAs(baselineFile)
  const baseline = JSON.parse(readFileSync(baselineFile, 'utf8'))
  await page.getByRole('tab', { name: '分析', exact: true }).click()
  await page.getByRole('button', { name: '空间处理', exact: true }).click()
  const panel = page.getByRole('region', { name: '空间处理参数' })
  await panel.getByRole('combobox', { name: '处理工具', exact: true }).selectOption('simplify')
  await panel.getByRole('spinbutton', { name: '简化容差（度）', exact: true }).fill('0.0001')
  await panel.getByLabel('结果图层名称', { exact: true }).fill('生产简化')
  await panel.getByRole('button', { name: '生成结果图层', exact: true }).click()
  const resultRow = page.locator('.layer-name-button').filter({ hasText: '生产简化' })
  await expect(resultRow).toBeVisible({ timeout: 60_000 })
  expect(cliResponses).toEqual([200])
  expect(remote).toEqual([])
  await panel.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(resultRow).toHaveCount(0)
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect(resultRow).toBeVisible()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  const file = info.outputPath('production.webgis.json')
  await (await downloading).saveAs(file)
  const saved = JSON.parse(readFileSync(file, 'utf8'))
  const result = saved.project.layers.find((layer: { name: string }) => layer.name === '生产简化')
  const original = saved.project.layers.find((layer: { name: string }) => layer.name === 'production')
  expect(saved.featuresByDataset[original.datasetId]).toEqual(baseline.featuresByDataset[original.datasetId])
  const originalCoordinates = baseline.featuresByDataset[original.datasetId][0].geometry.coordinates
  expect(saved.featuresByDataset[result.datasetId][0].geometry.coordinates).toEqual([originalCoordinates[0], originalCoordinates[2]])
  expect(saved.featuresByDataset[result.datasetId][0].properties).toEqual(properties)
  expect(saved.project.datasets.find((dataset: { id: string }) => dataset.id === result.datasetId).processing.engine).toEqual({ id: 'geolibre-wasm', version: '1.7.1', tool: 'simplify_features' })
  await page.getByRole('button', { name: '文件', exact: true }).click()
  const choosing = page.waitForEvent('filechooser')
  await page.getByRole('menuitem', { name: /^打开/ }).click()
  await (await choosing).setFiles(file)
  await expect(resultRow).toBeVisible()
  await resultRow.click()
  await page.getByRole('tab', { name: '数据', exact: true }).click()
  await page.getByRole('button', { name: '属性表', exact: true }).click()
  await expect(page.locator('.attribute-table-tab-panel:visible tbody')).toContainText('42')
})
